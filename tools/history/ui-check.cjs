'use strict';
// Optional browser integration check. Run with Electron; no desktop windows open.
const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises'), path = require('node:path'), os = require('node:os');
const profile = require('node:fs').mkdtempSync(path.join(os.tmpdir(), 'babble-history-ui-profile-'));
app.setPath('userData', profile);
const root = path.resolve(__dirname, '../..');
app.disableHardwareAcceleration();
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
const until = async fn => { for (let i = 0; i < 150; i++) { if (await fn()) return; await sleep(50); } throw new Error('Preview UI timed out'); };
const deadline = setTimeout(() => { console.error('UI test timed out'); app.exit(1); }, 40000);
app.whenReady().then(async () => {
  const { previewServer } = await import('./serve.mjs');
  const server = previewServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const win = new BrowserWindow({ show: false, width: 1366, height: 950, webPreferences: { offscreen: true, backgroundThrottling: false, sandbox: true, nodeIntegration: false, contextIsolation: true, spellcheck: false } });
  const run = code => win.webContents.executeJavaScript(code);
  const errors = [];
  win.webContents.on('console-message', event => { if (event.level === 'error' && !event.message.includes('503')) errors.push(event.message); });
  try {
    await win.loadURL(`http://127.0.0.1:${server.address().port}/history-preview.html`);
    await until(() => run(`document.querySelectorAll('.clues input[type=checkbox]').length===197`));
    assert.ok(await run(`document.querySelector('.grand').textContent.includes('2400 pts')`));
    assert.ok(await run(`document.body.textContent.includes('Last 7265 grids')`));
    assert.equal(await run(`document.querySelector('.page').getBoundingClientRect().width`), 718);
    assert.equal(await run(`getComputedStyle(document.body).fontFamily`), 'Georgia, serif');
    assert.equal(await run(`document.querySelectorAll('.record-date').length`), 2);
    assert.ok(await run(`!document.querySelector('aside').textContent.includes('Clues Administration') && !document.querySelector('aside').textContent.includes('History preview.')`));
    assert.equal(await run(`typeof window.AddBabbleWord`), 'function');
    assert.ok(await run(`document.documentElement.scrollWidth <= innerWidth`));
    await run(`document.querySelector('.clues input[type=checkbox]').click()`);
    await until(() => run(`document.querySelectorAll('.clues tr.done').length===1`));
    await win.webContents.reload();
    await until(() => run(`document.querySelectorAll('.clues tr.done').length===1`));
    const out = path.join(root, 'artifacts/history-preview');
    await fs.mkdir(out, { recursive: true });
    await sleep(100);
    await fs.writeFile(path.join(out, 'desktop.png'), (await win.webContents.capturePage()).toPNG());
    assert.equal(await run(`document.querySelector('.printable-link').getAttribute('href')`), '/history-preview.html?print=1');
    await win.loadURL(`http://127.0.0.1:${server.address().port}/history-preview.html?print=1`);
    await until(() => run(`document.querySelectorAll('.printable-clue').length===197`));
    assert.equal(await run(`document.querySelectorAll('input,textarea,.board,aside').length`), 0);
    assert.ok(await run(`document.querySelector('h1').textContent.includes('Puzzle 8608')`));
    assert.equal(await run(`document.querySelector('.printable-clue').textContent`), 'ad4,6');
    assert.ok(await run(`Array.from(document.querySelectorAll('.printable-clue')).every(row=>/^[a-z]{2}[0-9]+,[0-9]+$/.test(row.textContent))`));
    await fs.writeFile(path.join(out, 'printable.pdf'), await win.webContents.printToPDF({ printBackground: false }));
    win.webContents.debugger.attach('1.3');
    await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', {media:'print'});
    assert.equal(await run(`getComputedStyle(document.querySelector('.print-toolbar')).display`), 'none');
    await fs.writeFile(path.join(out, 'printable.png'), (await win.webContents.capturePage()).toPNG());
    await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', {media:'screen'});
    win.webContents.debugger.detach();
    await win.loadURL(`http://127.0.0.1:${server.address().port}/history-preview.html`);
    await until(() => run(`document.querySelectorAll('.clues input[type=checkbox]').length===197`));
    assert.equal(await run(`document.querySelector('.support-shortcut').getAttribute('href')`), '/history-admin.html');
    await run(`for(let i=0;i<4;i++) document.querySelector('.support-shortcut').click()`);
    assert.ok(win.webContents.getURL().endsWith('/history-preview.html'), 'Four clicks do not navigate');
    await sleep(2100);
    await run(`document.querySelector('.support-shortcut').click()`);
    assert.ok(win.webContents.getURL().endsWith('/history-preview.html'), 'Slow clicks reset the shortcut');
    await run(`for(let i=0;i<4;i++) document.querySelector('.support-shortcut').click()`);
    await until(() => run(`document.querySelector('.admin fieldset')`));
    assert.equal(await run(`document.querySelector('.admin fieldset').disabled`), true);
    await run(`Array.from(document.querySelectorAll('button')).find(button=>button.textContent==='Reload saved status').click()`);
    await until(() => run(`document.querySelector('[role=alert]')?.textContent.includes('previously displayed result has been kept')`));
    assert.ok(await run(`document.querySelector('.ok,.review').textContent.includes('197 words')`));
    assert.equal(await run(`Array.from(document.querySelectorAll('button')).find(button=>button.textContent==='Reload saved status').disabled`), false);
    assert.ok(await run(`document.body.textContent.includes('Find the extra word using stats')`));
    assert.ok(await run(`document.body.textContent.includes('Historical import exceptions')`));
    await run(`Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(document.querySelector('input[type=password]'), 'ui-test-key'); document.querySelector('input[type=password]').dispatchEvent(new Event('input', {bubbles:true}));`);
    await until(() => run(`!document.querySelector('.admin fieldset').disabled`));
    await run(`const field=document.querySelector('[aria-label="PlayBabble total words"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(field,'196'); field.dispatchEvent(new Event('input',{bubbles:true}));`);
    await until(() => run(`document.querySelector('.diagnostics').textContent.includes('1 extra')`));
    await run(`document.querySelector('.diagnostics details:last-of-type').open=true; document.querySelector('.diagnostics details:last-of-type button').click();`);
    await until(() => run(`document.querySelector('#correction-word').value==='adds'`));
    await win.webContents.reload();
    await until(() => run(`document.querySelector('[aria-label="PlayBabble total words"]')?.value==='196'`));
    assert.equal(await run(`document.querySelector('.admin fieldset').disabled`), true);
    win.setSize(390, 844); await sleep(150);
    assert.ok(await run(`document.documentElement.scrollWidth <= innerWidth`), 'Mobile page does not overflow horizontally');
    await fs.writeFile(path.join(out, 'mobile.png'), (await win.webContents.capturePage()).toPNG());
    assert.deepEqual(errors, []);
    console.log('PASS: familiar Self Serve frame, 197 clues, 2400 points, history, record dates, Expert bridge, found-word persistence, admin guide and lock, desktop/mobile admin. Screenshots: ' + out);
    win.destroy(); server.close(); clearTimeout(deadline); app.exit(0);
  } catch (error) { console.error(error); server.close(); app.exit(1); }
}).catch(error => { console.error(error); app.exit(1); });

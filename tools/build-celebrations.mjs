// Build the browser bundle and versioned Expert feed from the same renderer.
import fs from 'node:fs';
import vm from 'node:vm';
const root = new URL('../', import.meta.url);
const source = fs.readFileSync(new URL('public/celebration-effects.js', root), 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').trim();
const browserPath = new URL('public/clues-celebration.js', root);
let browser = fs.readFileSync(browserPath, 'utf8').replace(/\r\n/g, '\n');
const start = '/* BEGIN SHARED CELEBRATION EFFECTS */', end = '/* END SHARED CELEBRATION EFFECTS */';
browser = browser.slice(0, browser.indexOf(start)) + start + '\n' + source + '\n' + end + browser.slice(browser.indexOf(end) + end.length);
// These are build-time source functions, never evaluated by Expert's main process.
const fireworks = browser.slice(browser.indexOf('function createBabbleFireworks('), browser.indexOf(start)).trim();
const context = vm.createContext({});
vm.runInContext(fireworks + '\n' + source, context);
const catalog = context.createBabbleCelebration({ getContext: () => null });
const pack = { version: 1, effects: catalog.effects, labels: catalog.labels,
  renderer: context.createBabbleCelebration.toString(), fireworks: context.createBabbleFireworks.toString() };
if (!pack.effects.length || pack.effects.length > 100 || new Set(pack.effects).size !== pack.effects.length ||
    !pack.effects.every(id => /^[a-z][a-z0-9-]{0,39}$/.test(id)) || pack.labels.length !== pack.effects.length ||
    !pack.labels.every(label => typeof label === 'string' && label.length > 0 && label.length <= 80) ||
    Buffer.byteLength(JSON.stringify(pack) + '\n') > 512 * 1024) throw Error('Celebration catalog exceeds the v1 Expert contract');
const names = Object.fromEntries(catalog.effects.map((id, i) => [id, catalog.labels[i]]));
for (const [file, content] of [[browserPath, browser], [new URL('public/celebration-pack-v1.json', root), JSON.stringify(pack) + '\n'],
  [new URL('netlify/lib/celebration-catalog.mjs', root), '// Generated by tools/build-celebrations.mjs.\nexport const effectNames = Object.freeze(' + JSON.stringify(names, null, 2) + ');\n']]) {
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== content) throw Error('Run npm run celebrations:build: ' + file.pathname);
  } else fs.writeFileSync(file, content);
}
console.log('Browser celebrations and Expert pack match.');
